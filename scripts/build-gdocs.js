// Build gdocs/VersionView.html from public/lib/version-view.js (+ norm from ooxml.js),
// so the Google Docs sidebar uses the same tested view logic as the Word task pane.
// Apps Script has no modules: the code is wrapped into one global, RPView.
// Usage: npm run gdocs:build   (tests/gdocs-client.test.js fails if the file is stale)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = new URL("..", import.meta.url);
export const OUT = fileURLToPath(new URL("gdocs/VersionView.html", root));

export function buildVersionView() {
  const ooxml = readFileSync(new URL("public/lib/ooxml.js", root), "utf8");
  const normSrc = ooxml.match(/^export function norm\(s\) \{[\s\S]*?^\}/m);
  if (!normSrc) throw new Error("norm() not found in public/lib/ooxml.js");
  const view = readFileSync(new URL("public/lib/version-view.js", root), "utf8");
  const imports = view.match(/^import .*$/gm) || [];
  if (imports.length !== 1 || !/\{ norm \} from "\.\/ooxml\.js"/.test(imports[0])) {
    throw new Error("version-view.js imports changed: update scripts/build-gdocs.js");
  }
  const body = view.replace(/^import .*\n/m, "").replace(/^export /gm, "");
  return [
    "<!-- GENERATED by scripts/build-gdocs.js from public/lib/version-view.js. Do not edit; run npm run gdocs:build. -->",
    "<script>",
    "var RPView = (function () {",
    normSrc[0].replace(/^export /, ""),
    body.trim(),
    "return { versionView: versionView, gateClosed: gateClosed, untrackedUnits: untrackedUnits };",
    "})();",
    "</script>",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUT, buildVersionView());
  console.log(`wrote ${OUT}`);
}
