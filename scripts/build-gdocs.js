// Build gdocs/VersionView.html from public/lib/version-view.js (+ norm from ooxml.js,
// suggestionEdit and its helpers from diff.js),
// so the Google Docs sidebar uses the same tested view logic as the Word task pane.
// Apps Script has no modules: the code is wrapped into one global, RPView.
// Usage: npm run gdocs:build   (tests/gdocs-client.test.js fails if the file is stale)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = new URL("..", import.meta.url);
export const OUT = fileURLToPath(new URL("gdocs/VersionView.html", root));

/** Top-level function `name` from a module, without `export`. */
function fn(file, name) {
  const src = readFileSync(new URL(file, root), "utf8");
  const m = src.match(new RegExp(`^(export )?function ${name}\\([\\s\\S]*?^\\}`, "m"));
  if (!m) throw new Error(`${name}() not found in ${file}`);
  return m[0].replace(/^export /, "");
}

// diff.js helpers the sidebar uses directly (suggestionEdit and what it calls)
const DIFF = ["groupChanges", "wordDiff", "minimalEdit", "slideToWordStart", "suggestionEdit"];

export function buildVersionView() {
  const view = readFileSync(new URL("public/lib/version-view.js", root), "utf8");
  const imports = (view.match(/^import .*$/gm) || []).join("\n");
  if (imports !== 'import { norm } from "./ooxml.js";\nimport { suggestionEdit, wordDiff } from "./diff.js";') {
    throw new Error("version-view.js imports changed: update scripts/build-gdocs.js");
  }
  const body = view.replace(/^import .*\n/gm, "").replace(/^export /gm, "");
  return [
    "<!-- GENERATED by scripts/build-gdocs.js from public/lib/version-view.js. Do not edit; run npm run gdocs:build. -->",
    "<script>",
    "var RPView = (function () {",
    fn("public/lib/ooxml.js", "norm"),
    ...DIFF.map((name) => fn("public/lib/diff.js", name)),
    body.trim(),
    "return { versionView: versionView, gateClosed: gateClosed, untrackedUnits: untrackedUnits, suggestionEdit: suggestionEdit, reviewCards: reviewCards };",
    "})();",
    "</script>",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUT, buildVersionView());
  console.log(`wrote ${OUT}`);
}
